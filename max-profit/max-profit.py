print("=" * 65)

verification_tests = [0, 4, 5, 7, 8, 10, 13, 20, 30]

all_passed = True

for n in verification_tests:

    original_earnings, _, _ = solve(n)

    verified_earnings = verify_profit(n)

    status = "PASS" if original_earnings == verified_earnings else "MISMATCH"

    if status == "MISMATCH":
        all_passed = False

    print(
        f"Time={n:2d} | "
        f"Original=${original_earnings:,} | "
        f"Verified=${verified_earnings:,} | "
        f"{status}"
    )

