# ============================================================
# 6. INDEPENDENT VERIFICATION USING BOTTOM-UP DP
# ============================================================


def verify_profit(n):
    """
    Independently calculate maximum earnings using
    bottom-up dynamic programming.
    """

    if not isinstance(n, int) or isinstance(n, bool) or n < 0:
        raise ValueError("Time must be a non-negative integer.")

    buildings_list = [("T", 5, 1500), ("P", 4, 1000), ("C", 10, 2000)]

    # dp[t] stores the maximum earnings for time t.
    dp = [0] * (n + 1)

    for time in range(1, n + 1):

        for name, build_time, rate in buildings_list:

            if build_time <= time:

                remaining = time - build_time

                earnings = remaining * rate + dp[remaining]

                dp[time] = max(dp[time], earnings)

    return dp[n]


# ============================================================
# 7. COMPARE BOTH IMPLEMENTATIONS
# ============================================================

print("\n" + "=" * 65)
