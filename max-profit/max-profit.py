from functools import lru_cache

# ============================================================
# 1. BUILDING DETAILS
# ============================================================

# Each building has:
# Construction time and earnings per operational time unit.

buildings = {
    "T": (5, 1500),  # Theatre
    "P": (4, 1000),  # Pub
    "C": (10, 2000),  # Commercial Park
}


# ============================================================
# 2. ORIGINAL SOLUTION: RECURSION + MEMOIZATION
# ============================================================


@lru_cache(maxsize=None)
def best_profit(time_left):
    """
    Calculate maximum earnings for the available time.

    Returns:
        Maximum earnings and one optimal building sequence.
    """

    max_earnings = 0
    best_sequence = ()

    for name, (build_time, rate) in buildings.items():

        # Skip buildings that cannot be completed in time.
        if build_time > time_left:
            continue

        # Time remaining after construction.
        remaining = time_left - build_time

        # Earnings generated by this building.
        current_earnings = remaining * rate

        # Best earnings possible from the remaining time.
        future_earnings, future_sequence = best_profit(remaining)

        total_earnings = current_earnings + future_earnings

        # Keep the best sequence found.
        if total_earnings > max_earnings:
            max_earnings = total_earnings
            best_sequence = (name,) + future_sequence

    return max_earnings, best_sequence


# ============================================================
# 3. SOLVE FUNCTION WITH INPUT VALIDATION
# ============================================================


def solve(n):
    """
    Return maximum earnings, building counts,
    and one optimal building sequence.
    """

    if not isinstance(n, int) or isinstance(n, bool) or n < 0:
        raise ValueError("Time must be a non-negative integer.")

    earnings, sequence = best_profit(n)

    counts = {
        "T": sequence.count("T"),
        "P": sequence.count("P"),
        "C": sequence.count("C"),
    }

    return earnings, counts, sequence


# ============================================================
# 4. OFFICIAL EXAMPLE TEST CASES
